class Album {
  final String id;
  final String name;
  final String artistId;
  final String artistName;
  final String imageUrl;
  final String releaseDate;

  const Album({
    required this.id,
    required this.name,
    required this.artistId,
    required this.artistName,
    required this.imageUrl,
    required this.releaseDate,
  });
}
